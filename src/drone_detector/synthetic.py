"""Deterministic test signals. None are recordings or acoustic drone evidence."""

from pathlib import Path

import numpy as np
import soundfile as sf
from scipy import signal

from .common import write_json, write_jsonl


def generate_corpus(output, sessions_per_source=10, seed=20261108):
    output = Path(output)
    if output.exists():
        raise ValueError("Refusing to overwrite a synthetic corpus")
    if sessions_per_source < 5:
        raise ValueError("Need at least five synthetic sessions per generator")
    output.mkdir(parents=True)
    rate, seconds = 16000, 12
    t = np.arange(rate * seconds) / rate
    annotations = []
    for generator in range(3):
        for session in range(sessions_per_source):
            rng = np.random.default_rng(np.random.SeedSequence([seed, generator, session]))
            source = f"synthetic-generator-{generator}"
            base = rng.uniform(135, 220) + generator * 18
            for kind in ["positive", "ordinary_negative", "hard_negative"]:
                # Unique random waveforms, shared session and generator
                # provenance. Both labels use every generator and gain range.
                noise = signal.lfilter([1], [1, -0.85], rng.normal(size=len(t)))
                noise /= max(float(np.std(noise)), 1e-10)
                background = .025 * noise * (0.7 + 0.3 * np.sin(2 * np.pi * .4 * t) ** 2)
                events = []
                if kind == "positive":
                    mask = (t >= 4) & (t < 10)
                    envelope = np.zeros_like(t)
                    envelope[mask] = np.minimum(1, (t[mask] - 4) / .12) * np.minimum(1, (10 - t[mask]) / .12)
                    modulation = (3.1 + generator * .7)
                    phase = 2 * np.pi * base * t + 0.8 * np.sin(2 * np.pi * modulation * t)
                    tonal = sum(np.sin(k * phase + rng.uniform(-1, 1)) / k for k in range(1, 10))
                    audio = background + envelope * .12 * tonal
                    events = [[4.0, 10.0]]
                elif kind == "hard_negative":
                    # Intentionally confusable fan/motor-like tones. The truth
                    # is generator identity, not a claim to recognize real fans.
                    fan_base = rng.uniform(55, 115) if session % 2 else base * 1.2
                    phase = 2 * np.pi * fan_base * t + 0.15 * np.sin(2 * np.pi * 1.1 * t)
                    tonal = sum(np.sin(k * phase) / k for k in range(1, 8))
                    audio = background + .07 * tonal
                else:
                    sweeps = signal.chirp(t, f0=350, f1=2300, t1=seconds) * .01
                    audio = background + sweeps * np.sin(2 * np.pi * 1.8 * t) ** 4
                gain = 10 ** (rng.uniform(-16, 6) / 20)
                audio *= gain
                audio *= min(1, .95 / max(float(np.max(np.abs(audio))), 1e-12))
                identity = f"g{generator}-s{session:02d}-{kind}"
                relative = f"audio/{identity}.wav"
                (output / "audio").mkdir(exist_ok=True)
                sf.write(output / relative, audio, rate, subtype="PCM_16")
                annotations.append({
                    "id": identity, "path": relative, "source": source,
                    "source_version": f"generator-v1-seed-{seed}",
                    "session_id": f"g{generator}-s{session:02d}", "original_id": identity,
                    "origin": "synthetic", "label": "drone" if events else "non_drone",
                    "annotation_status": "verified_temporal" if events else "verified_negative",
                    "label_evidence": "Known signal generator, not audible/visual confirmation of a drone",
                    "events": events, "ambiguous": [], "device": None,
                    "environment": "synthetic signals", "drone_type": None,
                    "negative_kind": kind if not events else None,
                    "license": "MIT; generated by this repository",
                    "provenance_review": "Controlled generator; all derivatives retain generator/session lineage. No imported audio.",
                })
    write_jsonl(output / "annotations.jsonl", annotations)
    write_json(output / "generation.json", {
        "schema_version": 1, "seed": seed, "sessions_per_source": sessions_per_source,
        "recordings": len(annotations), "rate": rate, "duration_per_recording": seconds,
        "warning": "SOFTWARE/CONTROLLED SIGNAL TESTS ONLY. No authentic drone or environmental recordings.",
    })
    return output / "annotations.jsonl"
