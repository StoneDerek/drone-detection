#!/usr/bin/env python3
"""Prepare five retained browser excerpts for a software-only encoder smoke.

No external audio is downloaded. Publisher weak labels and original source
splits are retained; every example was already consumed during development.
"""

import argparse
import copy
import hashlib
import os
from pathlib import Path

import numpy as np

from drone_detector.audio import decode
from drone_detector.common import file_hash, read_json, read_jsonl, write_json, write_jsonl
from drone_detector.data import components, load_manifest

ROOT = Path(__file__).resolve().parents[1]
EXAMPLE_SHA256 = {
    "svanstrom-DRONE_001": "249e2a050cf8f79c6b18907e227f0f17af9013d1be727944e6b26cf88af90f8f",
    "svanstrom-HELICOPTER_001": "c4aa0f6382db091524f489d20a55ce4af30be56d074455cabc5b10b75c02c1d3",
    "svanstrom-BACKGROUND_001": "034a0d944030a49a705b264bb68035c914faa66d89365db10f4c251588f2152d",
    "batear-20260415_192501": "f4b8eaaa965570b6b268103846506adaaa0d87ff862af8d92ba0f9fab77f5bc9",
    "batear-20230701_054200": "2918011e0634fd06085059948025b8231d174366a147714223e311faaa3b4b2d"
}


def prepare_smoke(output):
    root, out = ROOT, Path(output).resolve()
    out.mkdir(parents=True, exist_ok=True)
    snapshot = root / 'reports/real-v2/manifest-snapshot.jsonl'
    catalog_path = root / 'web/public/examples/catalog.json'
    originals = {r['id']: r for r in read_jsonl(snapshot)}
    catalog = read_json(catalog_path)
    rows = []
    for item in catalog['examples']:
        old = originals[item['id']]
        audio_path = root / 'web/public' / item['public_example']
        if file_hash(audio_path) != EXAMPLE_SHA256[item['id']]:
            raise ValueError('Retained browser fixture changed: ' + item['id'])
        audio, info = decode(audio_path)
        row = copy.deepcopy(old)
        row.update(info)
        pcm = np.rint(audio.astype(np.float64) * 32767).clip(-32768, 32767).astype('<i2')
        peak = float(np.max(np.abs(audio)))
        normalized = np.rint(audio / max(peak, 1e-20) * 1024).astype('<i2')
        row.update({
            'id': old['id'] + '--browser-fixture',
            'path': os.path.relpath(audio_path, out),
            'sha256': file_hash(audio_path),
            'decoded_sha256': hashlib.sha256(pcm.tobytes()).hexdigest(),
            'gain_normalized_sha256': hashlib.sha256(normalized.tobytes()).hexdigest(),
            'parent_id': None,
            'events': [],
            'ambiguous': [],
            'annotation_status': 'weak',
            'label': item['publisher_label'],
            'label_evidence': old['label_evidence'] + '; browser excerpt inherits recording-level publisher class only; no claim that drone is audible throughout excerpt',
            'duplicate_review_required': False,
            'provenance_review': old['provenance_review'] + '; retained browser derivative generated by scripts/observe_real_audio.py: canonical mono16kHz, first up-to10s, PCM16. Parent source/recording/session retained. Software-only smoke; no new independent assessment.',
            'derivative': {
                'parent_record_id': old['id'],
                'parent_manifest_sha256': file_hash(snapshot),
                'parent_audio_sha256': old['sha256'],
                'parent_duration_seconds': old['duration_seconds'],
                'excerpt_start_seconds': item['excerpt_start_seconds'],
                'excerpt_duration_seconds': item['excerpt_duration_seconds'],
                'transforms': ['decode arithmetic channel mean', 'polyphase resample16kHz', 'crop first up-to10s', 'PCM16 export'],
                'producer': 'scripts/observe_real_audio.py',
                'producer_sha256': file_hash(root / 'scripts/observe_real_audio.py'),
            },
            'experiment_scope': 'software-smoke-only; all examples already consumed for development; no field/generalization claim',
            'quality_flags': [],
        })
        assert abs(row['duration_seconds'] - item['excerpt_duration_seconds']) < 1 / 16000
        rows.append(row)
    for row, group in zip(rows, components(rows), strict=True):
        row['group_id'] = group
    candidate = out / 'manifest.partial.jsonl'
    write_jsonl(candidate, rows)
    if (out / 'manifest.jsonl').exists() and (out / 'manifest.jsonl').read_bytes() != candidate.read_bytes():
        candidate.unlink()
        raise ValueError('Existing smoke manifest changed; use a new output directory')
    candidate.replace(out / 'manifest.jsonl')
    validated = load_manifest(out / 'manifest.jsonl', require_split=True)
    assert {r['split'] for r in validated} == {'train', 'development'}
    write_json(out / 'manifest-receipt.json', {
        'scope': 'software-smoke-only on retained already-consumed browser audio; no new independent acoustic evidence',
        'manifest_sha256': file_hash(out / 'manifest.jsonl'),
        'source_snapshot_sha256': file_hash(snapshot),
        'catalog_sha256': file_hash(catalog_path),
        'recordings': len(rows),
        'train': [r['id'] for r in rows if r['split'] == 'train'],
        'development': [r['id'] for r in rows if r['split'] == 'development'],
        'groups': sorted({r['group_id'] for r in rows}),
        'verified_temporal_annotations': 0,
        'recording_metrics_only': True,
        'limitations': 'Three related Svanstrom training files and two Batear development files; labels inherited from whole recordings, not audibility-confirmed intervals; browser conversion changes original hashes. Too small for model or threshold selection claims.'
    })
    return out / 'manifest.jsonl'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    print(prepare_smoke(args.output))


if __name__ == '__main__':
    main()
